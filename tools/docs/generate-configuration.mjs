import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import config from '../../libs/config/src/index.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const output = resolve(root, 'docs/configuration.md')

// Defaults of fields matching this are replaced by a dash, so a credential committed to the schema never reaches the docs
const SENSITIVE = /key|token|secret|password|credential|identifier|pin/i

const masked = []

const escape = (value) => String(value).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ')
const code = (value) => `\`${escape(value)}\``
const capitalize = (value) => `${value[0].toUpperCase()}${value.slice(1)}`

const isLeaf = (node) => typeof node === 'object' && node !== null && 'default' in node
const isItem = (node) => typeof node === 'object' && node !== null && ('default' in node || 'format' in node)

const renderType = (node) =>
  Array.isArray(node.format) ? node.format.map(code).join(', ') : node.format ? code(node.format) : '—'

const renderDefault = (node, path) => {
  if (node.sensitive === true || SENSITIVE.test(path)) {
    if (typeof node.default === 'string' && node.default !== '') {
      masked.push(path)
      return '—'
    }
  }

  if (node.default === undefined) {
    return '—'
  }

  return code(typeof node.default === 'string' ? node.default || '""' : JSON.stringify(node.default))
}

const walk = (node, path, rows) => {
  if (node._cvtProperties) {
    for (const [key, child] of Object.entries(node._cvtProperties)) {
      walk(child, path ? `${path}.${key}` : key, rows)
    }

    return rows
  }

  if (isLeaf(node)) {
    rows.push([code(path), renderType(node), renderDefault(node, path), escape(node.doc || '—')])

    // "source-array" fields describe their items with a "children" key, either a map of named fields or a single item
    if (typeof node.children === 'object' && node.children !== null) {
      if (isItem(node.children)) {
        walk(node.children, `${path}[]`, rows)
      } else {
        for (const [key, child] of Object.entries(node.children)) {
          walk(child, `${path}[].${key}`, rows)
        }
      }
    }

    return rows
  }

  for (const [key, child] of Object.entries(node)) {
    walk(child, `${path}.${key}`, rows)
  }

  return rows
}

const schema = config.getSchema()._cvtProperties
const scalars = Object.entries(schema).filter(([, node]) => isLeaf(node) && !node.children)
const sections = Object.entries(schema).filter(([, node]) => !isLeaf(node) || node.children)

const table = (rows) =>
  ['| Name | Type | Default | Description |', '| --- | --- | --- | --- |', ...rows.map((row) => `| ${row.join(' | ')} |`)].join('\n')

const tables = [
  ['General', scalars.flatMap(([key, node]) => walk(node, key, []))],
  ...sections.map(([key, node]) => [capitalize(key), walk(node, key, [])]),
]

const lines = [
  '# Configuration reference',
  '',
  '*Generated by `node tools/docs/generate-configuration.mjs` from `libs/config/src/index.js`, do not edit by hand.*',
  '',
  'Values live in `config.json`, read by the API (`apps/api/src/app/config/config.service.ts`), `config.default.json` is the starting point.',
  'A `[]` in a name stands for one item of the array above it.',
  ...tables.flatMap(([title, rows]) => ['', `## ${title}`, '', table(rows)]),
]

mkdirSync(dirname(output), { recursive: true })
writeFileSync(output, `${lines.join('\n')}\n`)

const fields = tables.reduce((total, [, rows]) => total + rows.length, 0)
console.log(`Wrote ${output} (${fields} fields)${masked.length ? `, masked default of ${masked.join(', ')}` : ''}`)
